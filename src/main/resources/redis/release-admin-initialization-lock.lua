-- 관리자 초기화가 획득한 락만 해제한다.
-- KEYS[1]: 모든 인스턴스가 공유하는 관리자 초기화 락 키.
-- ARGV[1]: 이번 획득 시도에서 생성한 고유 소유자 토큰(UUID).
-- 반환값: 1 = 자신의 락을 삭제함, 0 = 키가 없거나 다른 소유자의 락이므로 유지함.
-- KEYS와 ARGV는 Redis가 제공하는 입력 배열이며 인덱스는 1부터 시작한다.

-- GET 결과가 소유자 토큰과 같을 때만 DEL을 실행한다.
-- 조회와 삭제가 하나의 스크립트로 실행되어 두 명령 사이에 다른 요청이 끼어들지 않는다.
-- 만료 후 다른 인스턴스가 재획득한 락을 이전 소유자가 삭제하는 것을 방지한다.
if redis.call('GET', KEYS[1]) == ARGV[1] then
    return redis.call('DEL', KEYS[1])
end

-- 키가 없을 때 GET은 false를 반환하므로 이 경로로 끝난다.
return 0
